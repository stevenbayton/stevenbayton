      SUBROUTINE CIRCLE(BB,BH,UH,BEV,BEH,BV,UV,R)
C
C     THIS SUBROUTINE CALCULATE THE GEOMETRY OF THE CIRCLE - CARL
C
C     NOVEMBER 1984 -ARNE KVITRUD , NGI
C
C     INPUT
C       BH = HORISONTAL AVSTAND FRA SIRKELSENTER TIL HOYRE SKJOERTEKANT
C       UH = GLIDEFLATEDYBDE FRA SKJOERTESPISS, HOYRE
C       BB = BREDDE AV FUNDAMENTET I BOELGERETNINGEN
C
C     OUTPUT
C       BEV= VINKEL MELLOM VERTIKALEN OG VENSTRE KANT AV SIRKELGLIDEFLATEN
C       BEH= DET SAMME FOR HOYRE SIDE
C       BV = HORISONTAL AVSTAND FRA SIRKELSENTERET TIL VENSTRE SKJORTEKANT
C       UV = GLIDEFLATEDYBDE FRA SKJOERTESPISS, VENSTRE
C       R  = SIRKELRADIUS
C
      R=(BH*BH-UH*UH)/(2.*UH)
      BV=BB-BH
      UV=SQRT(BV*BV+R*R)-R
      BEV=ATAN(BV/R)
      BEH=ATAN(BH/R)
      RETURN
      END
