      SUBROUTINE FORCE(PV,ZS,BB,AL,UH,BH,PH,AM,DELPH,DELPT,GAMS,GAMW,
     1                 RUV,RUH,F,SA,A,B)
C
C     THIS SUBROUTINE CALCULATES ALL THE A- AND B-VALUES IN THE
C     GENERAL EQUATIONS FOR THE FORCES
C
C     2.ND EDITION NOVEMBER 1984
C
C         INPUT
C            PV,  ZS, BB, AL, UH, BH, PH, AM, DELPH, DELPT, GAMS, GAMW,
C            RUV,RUH,F,SA
C
C         OUTPUT
C           A, B
C
      DIMENSION  A(20) , B(20), F(16), SA(20)
      REAL KCH,KCV
C
      PI = 4.*ATAN(1.)
      R2 = SQRT (2.)
      GAM1 = GAMS - GAMW
      R = (BH*BH-UH*UH)/(2.*UH)
      BV = BB-BH
      UV = SQRT(BV*BV+R*R)-R
      BEV = ATAN(BV/R)
      BEH = ATAN(BH/R)
C
C     KCV = JORDTRYKKSFAKTOR, VENSTRE
C     KCH = JORDTRYKKSFAKTOR, HOYRE
C     WV  = JANBUVINKEL ,VENSTRE
C     WH  = JANBUVINKEL ,HOYRE
C
      IF ( RUV ) 20,10,20
   10 CONTINUE
      WV =0.0
      GOTO 30
   20 CONTINUE
      WV = ATAN((1.-SQRT(1.-RUV*RUV))/RUV)
   30 CONTINUE
      IF ( RUH ) 50,40,50
   40 CONTINUE
      WH =0.0
      GOTO 60
   50 CONTINUE
      WH = ATAN((1.-SQRT(1.-RUH*RUH))/RUH)
   60 CONTINUE
      KCV=1.+2.*WV+SQRT(1.-RUV*RUV)
      KCH = 1.+2.*WH+SQRT(1.-RUH*RUH)
      UP = R+ZS*F(16)/2.
      ATS = ZS*ZS*(1.+F(4))+2.*R2*ZS*(UH+UV*F(4))+BB*R+(1.+PI/4.)*(UV*UV
     1+UH*UH)+BEV*UV*UV-(BEV+BEH)*R*R+BEH*UH*UH
C
C     FORCES:
C
      A(1) = 0.
      B(1) = AM+PH*ZS
C
      A(2) = 0.
      B(2) = (PV+GAMS*BB*AL*ZS)*(BH-BB/2.)
C
      A(3) = 0.
      B(3) = PH*R
C
      A(4) = -F(4)*KCV*ZS*AL*(R+ZS*F(14)/2.)
      B(4) = DELPH*ZS*AL*(R+ZS/2.)
     1       +(ZS*ZS*AL/2.)*(GAM1*F(4)+GAMW)*(R+ZS/3.)
C
      A(5) = -KCH*ZS*AL*(R+ZS*F(15)/2.)
      B(5) = -DELPT*ZS*AL*(R+ZS/2.)-(GAMS*ZS*ZS*AL/2.)*(R+ZS/3.)
C
      A(6) = -ZS*AL*F(6)*(F(4)*BV+BH)
      B(6) = 0.
C
      A(7) = -(2.*BEV+(2.+PI)/2.)*UV*AL*(R+UV/2.)
      B(7) = (DELPH+GAMS*ZS)*UV*AL*(R+UV/2.)
     1       +(GAMS*UV*UV*AL/2.)*COS(BEV)*(R+UV/3.)
C
      A(8) = -(2.*BEH+(2.+PI)/2.)*UH*AL*(R+UH/2.)
      B(8) = -(DELPT+GAMS*ZS)*UH*AL*(R+UH/2.)
     1       -(GAMS*UH*UH*AL/2.)*COS(BEH)*(R+UH/3.)
C
      A(9) = -(BEV+BEH)*R*R*AL
      B(9) = 0.
C
      A(10) = -(ZS*F(10)/1.)*(BH*SQRT(UP*UP+BH*BH)
     1        +UP*UP*ALOG(BH+SQRT(UP*UP+BH*BH))+BV*SQRT(UP*UP+BV*BV)
     1        -UP*UP*ALOG(SQRT(UP*UP+BV*BV)-BV))
      B(10) = 0.
C
C
C     KONTROLLERER AT MAN IKKE FAAR DELING PAA NULL
C
      IF ( SA(11) ) 100,100,110
  100 CONTINUE
      A(11)=0.0
      B(11)=0.0
      GOTO 120
  110 CONTINUE
      A(11) = -F(11)*SA(20)*2./SA(11)
      B(11) = 0.
  120 CONTINUE
C
      A(12) = 0.
      B(12) = GAMS*R*R*R*((SIN(BEH)*SIN(BEH)-
     1        SIN(BEV)*SIN(BEV))/2.+(COS(BEH)*COS(BEH)*COS(BEH)-
     1        COS(BEV)*COS(BEV)*COS(BEV))/3.)*AL
     1        +(GAMS*AL/2.)*(UH*UH*SIN(BEH)*COS(BEH)*
     1        (BH-2.*UH*SIN(BEH)/3.)-UV*UV*SIN(BEV)*COS(BEV)
     1        *(BV-2.*UV*SIN(BEV)/3.))
C
      A(13) = 0.
      B(13) = 0.
C
      A(14) = 0.
      B(14) = 0.
C
      A(15) = 0.
      B(15) = 0.
C
      A(16) = 0.
      B(16) = 0.
C
      A(17) = 0.
      B(17) = 0.
C
      A(18) = 0.
      B(18) = 0.
C
      A(19) = 0.
      B(19) = 0.
C
      A(20) = 0.
      B(20) = 0.
C
      RETURN
      END
