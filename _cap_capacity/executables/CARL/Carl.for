      SUBROUTINE SAF2(PV,ZS,BB,AL,UH,BH,PH,AM,DELPH,DELPT,NSU,ZZZ,SU,
     1                SUD,SUP,SU2,GAMS,GAMW,RUV,RUH,F,
     2                SF,CSS,SUMB)
C
C     CALCULATES THE SAFETY FACTOR FOR A GIVEN DATA SET
C
C     2.ND REVISION NOVEMBER 1984
C
C         INPUT
C           PV,  ZS, BB, AL,UH,BH,PH,AM DELPH, DELPT, NSU, ZZZ, SU, SUD,
C           SUP, SU2, GAMS, GAMW,RUV,RUH,F
C
C         OUTPUT
C           SF, CSS, SUMB
C
      DIMENSION  ZZZ(50) , SU(50) , SUD(50) , SUP(50) , SU2(50), F(16)
C
      DIMENSION  A(20), B(20), SA(20)
C
C
      N = 20
C
      CALL SHEAR2(BB,BH,ZS,UH,NSU,ZZZ,SU,SUD,SUP,SU2,F,SA)
      CALL FORCE(PV,ZS,BB,AL,UH,BH,PH,AM,DELPH,DELPT,GAMS,GAMW,RUV,
     1           RUH,F,SA,A,B)
C
      SUMA = 0.
      SUMB = 0.
      SUMAS = 0.
C
      DO 1000 I=1,N
      SUMA = SUMA + A(I)
      SUMB = SUMB + B(I)
      SUMAS = SUMAS + A(I)*SA(I)
 1000 CONTINUE
C
      SF = SUMAS / (-SUMB)
      CSS = - SUMB/SUMA
C
      RETURN
      END
       SUBROUTINE SUBS(ZZZ,SU,NSU,Z,SS)
C
C              MARTIN HUNDSTAD     UNIVAC 1110              27 DES 76
C
C         INPUT
C
C           ZZZ    - ARRAY MED DYBDE-VERDIER.
C           SU     - ARRAY MED TILH@RENDE SKJ#RFASTHET-VERDIER.
C           NSU    - ANTALL VERDIER I -ZZZ- OG -SU- ARRAYS.
C           Z      - GITT DYBDE.
C
C         OUTPUT
C
C           SS     - BEREGNET SKJ#RFASTHET VED GITT DYBDE ( INTERPOLASJON ).
C
C
      DIMENSION  ZZZ(50) , SU(50)
      N=0
  200 N=N+1
      IF (N .GT. NSU) GO TO 300
      IF (Z - ZZZ(N)) 240,220,200
C
  220 SS=SU(N)
      GO TO 500
  240 IF (N .GT. 1) GO TO 250
      SS=SU(1)
      GO TO 500
  250 SS=SU(N-1)+(SU(N)-SU(N-1))/(ZZZ(N)-ZZZ(N-1))*(Z-ZZZ(N-1))
      GO TO 500
C
  300 SS=SU(NSU)
C
  500 RETURN
      END

      SUBROUTINE SHEAR2(BB,BH,ZS,UH,NSU,ZZZ,SU,SUD,SUP,SU2,F,SA)
C
C     CALCULATES ALL THE AVERAGE SHEAR STRENGHT VALUES TO BE USED
C     IN THE GENERAL EQUATION FOR THE FORCES
C
C     2.ND REVISION NOVEMBER 1984 -CARL
C
C         INPUT
C           BB, BH, ZS, Z, NSU, ZZZ, SU, SUD, SUP, SU2, F
C
C         OUTPUT
C           SA
C           I TILLEGG ENDRER F VERDI I SUBRUTINEN
C
C           EXTERNAL CALLS : SUBS,CIRCLE
C
      DIMENSION SA(20),SU(50),SUD(50),SUP(50),SU2(50),ZZZ(50)
     1          ,F(16)
      DIMENSION  U(64), DELB(64), BL(64), BET(64), SUI(64),SUS(64)
     1           ,Y(64)
C
      SA(1) = 0.
      SA(2) = 0.
      SA(3) = 0.
      DO 900 I = 13,19
      SA(I) = 0.
  900 CONTINUE
C
      R2 = SQRT(2.)
      PI = 4.*ATAN(1.)
      CALL CIRCLE(BB,BH,UH,BEV,BEH,BV,UV,R)
      SA(4) = 0.
      SA(5) = 0.
      SA(6) = 0.
      F(14) = 0.
      F(15) = 0.
      F(16) = 0.
C
      DELZ = ZS/10.
      DZ = -DELZ/2.
      DO 1000 I = 1,10
      DZ = DZ+DELZ
      CALL SUBS(ZZZ,SU,NSU,DZ,SS)
      SA(4) = SA(4)+SS
      F(14) = F(14)+SS*DELZ*(ZS-DZ)
      CALL SUBS(ZZZ,SUP,NSU,DZ,SS)
      SA(5) = SA(5)+SS
      F(15) = F(15)+SS*DELZ*(ZS-DZ)
      CALL SUBS(ZZZ,SUD,NSU,DZ,SS)
      SA(6) = SA(6)+SS
      F(16) = F(16)+SS*DELZ*(ZS-DZ)
 1000 CONTINUE
      SA(4) = .1*SA(4)
