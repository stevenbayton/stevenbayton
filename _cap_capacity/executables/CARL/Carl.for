      SUBROUTINE HORF2(PV,ZS,BB,AL,UH,BH,PH,AM,DELPH,DELPT,NSU,ZZZ,SU
     1                ,SUD,SUP,SU2,GAMS,GAMW,RUV,RUH,F,
     2                SF,CSS,SUMB)
C
C     CALCULATES THE HORISONTAL FORCE FOR A GIVEN DATASET,
C     INCLUDED SAFETYFACTOR = 1.0
C
C     MADE BY ARNE KVITRUD,NGI DECEMBER 1984
C
C
C
C         INPUT
C           PV,  ZS, BB, AL,UH,BH,AM DELPH, DELPT, NSU, ZZZ, SU, SUD,
C           SUP, SU2, GAMS, GAMW,RUV,RUH,F
C
C         OUTPUT
C           SF, CSS, SUMB, PH
C
C     EXTERNAL CALLS : SHEAR2 & FORCE
C
      DIMENSION  ZZZ(50) , SU(50) , SUD(50) , SUP(50) , SU2(50), F(16)
C
      DIMENSION  A(20), B(20), SA(20)
C
C
      N = 20
C
      CALL SHEAR2(BB,BH,ZS,UH,NSU,ZZZ,SU,SUD,SUP,SU2,F,SA)
      CALL FORCE(PV,ZS,BB,AL,UH,BH,PH,AM,DELPH,DELPT,GAMS,GAMW,RUV,
     1           RUH,F,SA,A,B)
C
      SUMA = 0.
      SUMB = 0.
      SUMAS = 0.
C
      DO 1000 I=1,12
      SUMAS = SUMAS + A(I)*SA(I)
 1000 CONTINUE
      SUMB=B(2)
      DO 1100 I=4,12
      SUMB=SUMB+B(I)
 1100 CONTINUE
      R=(BH*BH-UH*UH)/(2.0*UH)
      PH=-(SUMAS+SUMB)-AM
      PH=PH/(R+ZS)
C
C
      RETURN
      END
